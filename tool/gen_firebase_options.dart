// Writes lib/firebase_options.dart from the files downloaded in the Firebase
// console.
//
//   dart run tool/gen_firebase_options.dart
//
// Reads android/app/google-services.json (required) and
// ios/Runner/GoogleService-Info.plist (optional).

import 'dart:convert';
import 'dart:io';

const packageId = 'com.kabeerkhanniazi.fithabit';

void main() {
  final androidFile = File('android/app/google-services.json');
  if (!androidFile.existsSync()) {
    stderr.writeln('Missing ${androidFile.path}. Download it from the Firebase '
        'console (Project settings > Your apps > Android app).');
    exit(1);
  }

  final json = jsonDecode(androidFile.readAsStringSync()) as Map<String, dynamic>;
  final project = json['project_info'] as Map<String, dynamic>;
  final clients = (json['client'] as List).cast<Map<String, dynamic>>();
  final client = clients.firstWhere(
    (c) => c['client_info']['android_client_info']['package_name'] == packageId,
    orElse: () {
      stderr.writeln('google-services.json has no Android app with the '
          'package name $packageId.');
      exit(1);
    },
  );

  final android = {
    'apiKey': client['api_key'][0]['current_key'] as String,
    'appId': client['client_info']['mobilesdk_app_id'] as String,
    'messagingSenderId': project['project_number'] as String,
    'projectId': project['project_id'] as String,
    if (project['storage_bucket'] != null)
      'storageBucket': project['storage_bucket'] as String,
  };

  // iOS is optional. Without its file the Android values are reused, which
  // lets the code compile; an iPhone build needs the real file.
  var ios = {...android, 'iosBundleId': packageId};
  final iosFile = File('ios/Runner/GoogleService-Info.plist');
  if (iosFile.existsSync()) {
    final plist = iosFile.readAsStringSync();
    String? value(String key) => RegExp(
            '<key>$key</key>\\s*<string>([^<]*)</string>')
        .firstMatch(plist)
        ?.group(1);
    ios = {
      'apiKey': value('API_KEY') ?? android['apiKey']!,
      'appId': value('GOOGLE_APP_ID') ?? android['appId']!,
      'messagingSenderId': value('GCM_SENDER_ID') ?? android['messagingSenderId']!,
      'projectId': value('PROJECT_ID') ?? android['projectId']!,
      if (value('STORAGE_BUCKET') != null) 'storageBucket': value('STORAGE_BUCKET')!,
      'iosBundleId': value('BUNDLE_ID') ?? packageId,
    };
  } else {
    stdout.writeln('No ${iosFile.path}: iOS will reuse the Android values.');
  }

  String options(Map<String, String> values) => values.entries
      .map((e) => "    ${e.key}: '${e.value}',")
      .join('\n');

  File('lib/firebase_options.dart').writeAsStringSync('''
// Firebase keys for this app.
//
// GENERATED by tool/gen_firebase_options.dart. Do not edit by hand.
//
// These values identify the Firebase project; they are not passwords.
// Access to data is controlled by firestore.rules.

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

abstract final class DefaultFirebaseOptions {
  static const isConfigured = true;

  static FirebaseOptions get currentPlatform {
    if (kIsWeb) return android;
    return switch (defaultTargetPlatform) {
      TargetPlatform.iOS => ios,
      _ => android,
    };
  }

  static const android = FirebaseOptions(
${options(android)}
  );

  static const ios = FirebaseOptions(
${options(ios)}
  );
}
''');
  stdout.writeln('Wrote lib/firebase_options.dart for project '
      '${android['projectId']}.');
}
